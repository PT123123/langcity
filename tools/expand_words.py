def to_romaji(kana: str) -> str:
    out = []
    i = 0
    while i < len(kana):
        ch = kana[i]
        if ch == "ー" and out:  # 长音符：重复前一个元音
            prev = out[-1]
            m = re.search(r"[aiueo]$", prev)
            if m:
                out.append(m.group(0))
                i += 1
                continue
        if ch == "っ" or ch == "ッ":  # 促音：双写后续辅音
            nxt = kana[i + 1] if i + 1 < len(kana) else ""
            r = KANA_ROMA.get(nxt, "")
            c = r[0] if r else ""
            out.append("t" if r.startswith("ch") else c)
            i += 1
            continue
        two = kana[i:i + 2]
        if two in KANA_ROMA:
            out.append(KANA_ROMA[two])
            i += 2
            continue
        if ch in SMALL_YOUON:  # 小假名直接跟在后面（如 ー 后）
            i += 1
            continue
        r = KANA_ROMA.get(ch)
        if r is None:
            raise ValueError("未映射假名: %r in %s" % (ch, kana))
        out.append(r)
        i += 1
    return "".join(out)


def main() -> None:
    old = json.load(io.open(WORDS_PATH, encoding="utf-8"))
    old_ids = {w["id"] for w in old["words"]}

    cats = old["categories"]
    have_cat = {c["id"] for c in cats}
    for c in NEW_CATEGORIES:
        if c["id"] not in have_cat:
            cats.append(c)

    words = list(old["words"])  # 保留原 48 词（含 audio 字段）
    seen = {w["id"] for w in words}
    added = 0
    for entry in NEW_WORDS:
        ja, kana, zh, cat = entry[0], entry[1], entry[2], entry[3]
        wid = entry[4] if len(entry) > 4 else to_romaji(kana)
        if wid in old_ids:
            raise ValueError("id 与原词冲突: %s (%s)" % (wid, ja))
        if wid in seen:
            raise ValueError("新词 id 重复: %s (%s)" % (wid, ja))
        seen.add(wid)
        words.append({
            "id": wid,
            "ja": ja,
            "kana": kana,
            "romaji": to_romaji(kana),
            "zh": zh,
            "category": cat,
            "audio": "res://assets/audio/%s.mp3" % wid,
        })
        added += 1

    out = {"categories": cats, "words": words}
    io.open(WORDS_PATH, "w", encoding="utf-8", newline="\n").write(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n")
    print("新增 %d 词，总数 %d（原 %d）" % (added, len(words), len(old["words"])))
    by_cat = {}
    for w in words:
        by_cat[w["category"]] = by_cat.get(w["category"], 0) + 1
    for c in cats:
        print("  %-10s %d" % (c["id"], by_cat.get(c["id"], 0)))


